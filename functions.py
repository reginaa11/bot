# --- Функция 1: ПАРСИНГ синонимов (работает с русским) ---
def get_synonyms_bs4(word):
    print(f"[Скрапинг] Ищу синонимы для: {word}")
    try:
        # Используем другой сайт для русских синонимов
        encoded_word = urllib.parse.quote(word)
        url = f"https://synonyms.info/{encoded_word}"
        
        headers = {
            'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36'
        }
        
        response = requests.get(url, headers=headers, timeout=10)
        soup = BeautifulSoup(response.text, 'html.parser')
        
        # Ищем блок с синонимами на synonyms.info
        synonyms_list = []
        
        # Способ 1: ищем теги <a> с классом synonym
        for a in soup.find_all('a', class_='synonym'):
            syn = a.text.strip()
            if syn and syn != word and len(syn) > 1:
                synonyms_list.append(syn)
        
        # Способ 2: ищем все ссылки в основном контенте
        if not synonyms_list:
            content = soup.find('div', class_='content') or soup.find('main')
            if content:
                links = content.find_all('a')
                for link in links:
                    text = link.text.strip()
                    if text and len(text) > 2 and text != word:
                        synonyms_list.append(text)
        
        # Убираем дубликаты и ограничиваем 10 штуками
        synonyms_list = list(dict.fromkeys(synonyms_list))[:10]
        
        if synonyms_list:
            return "🔗 *Синонимы к слову '" + word + "':*\n" + ", ".join(synonyms_list)
        else:
            # Резервный вариант: словарь встроенных синонимов
            builtin_synonyms = get_builtin_synonyms(word)
            if builtin_synonyms:
                return "🔗 *Синонимы к слову '" + word + "':*\n" + ", ".join(builtin_synonyms)
            return f"😕 Не удалось найти синонимы для '{word}'\nПопробуй другое слово."
            
    except Exception as e:
        print(f"Ошибка парсинга: {e}")
        # Резервный вариант
        builtin = get_builtin_synonyms(word)
        if builtin:
            return "🔗 *Синонимы (встроенный словарь):*\n" + ", ".join(builtin)
        return f"⚠️ Ошибка при поиске синонимов. Попробуй слово: красивый, хороший, большой"

